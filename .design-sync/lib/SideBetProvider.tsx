// Design-canvas stand-in for the app's provider stack (Auth, Profile, BetData,
// EventCheckIn, Notification). It feeds the app's REAL context objects with
// static sample values, so components that call useAuth() / useBetData() /
// useProfile() render a signed-in state without AWS. Every value can be
// overridden through props.
//
// The context objects are module-private in src/contexts/*; build.mjs appends
// an export for each at bundle time (contextExports plugin) - app source is
// not modified. The @ts-expect-error lines below are for that reason.

import React, { useMemo } from 'react';
import { SafeAreaProvider } from 'react-native-safe-area-context';
import { View } from 'react-native';
import { NavigationContainer, NavigationIndependentTree } from '@react-navigation/native';
import { Amplify } from 'aws-amplify';
// Generated by build.mjs: the app's data schema with an unreachable endpoint.
import canvasAmplifyConfig from 'sidebet-canvas-amplify-config';
import { colors } from '../../src/styles';
// @ts-expect-error - export added at bundle time by build.mjs
import { AuthContext } from '../../src/contexts/AuthContext';
// @ts-expect-error - export added at bundle time by build.mjs
import { ProfileContext } from '../../src/contexts/ProfileContext';
// @ts-expect-error - export added at bundle time by build.mjs
import { BetDataContext } from '../../src/contexts/BetDataContext';
// @ts-expect-error - export added at bundle time by build.mjs
import { EventCheckInContext } from '../../src/contexts/EventCheckInContext';
// @ts-expect-error - export added at bundle time by build.mjs
import { NotificationContext } from '../../src/contexts/NotificationContext';
import type { Bet, BetInvitation, SquaresInvitation } from '../../src/types/betting';
import type { LiveEvent } from '../../src/types/events';

export interface SideBetUser {
  userId: string;
  username: string;
  displayName?: string;
  role?: 'USER' | 'ADMIN' | 'SUPER_ADMIN';
  profilePictureUrl?: string;
  subscriptionTier?: 'FREE' | 'PRO';
}

/** Mirrors BetDataContext's (module-private) SquaresGame shape. */
export interface SideBetSquaresGame {
  id: string;
  creatorId: string;
  eventId: string;
  title: string;
  description?: string;
  status: string;
  pricePerSquare: number;
  totalPot: number;
  squaresSold: number;
  numbersAssigned: boolean;
  isPrivate?: boolean;
  createdAt: string;
}

export interface SideBetProviderProps {
  children?: React.ReactNode;
  /** Signed-in user. Pass null to render signed-out states. Default: "Jordan Miles". */
  user?: SideBetUser | null;
  /** Account balance in dollars shown by Header / UserBalance. Default 250. */
  balance?: number;
  /** Bets the viewer created or joined (BetDataContext.myBets). */
  myBets?: Bet[];
  /** Bets the viewer can join (BetDataContext.joinableBets). */
  joinableBets?: Bet[];
  /** Pending bet invitations for the viewer. */
  betInvitations?: BetInvitation[];
  /** Pending squares-game invitations for the viewer. */
  squaresInvitations?: SquaresInvitation[];
  /** Squares games the viewer created or bought into. */
  mySquaresGames?: SideBetSquaresGame[];
  /** Squares games the viewer can join. */
  joinableSquaresGames?: SideBetSquaresGame[];
  /** Side + stake the viewer holds per bet id, e.g. { 'bet-1': { side: 'A', amount: 20 } }. */
  myParticipation?: Record<string, { side: string; amount: number }>;
  /** User ids the viewer is friends with. */
  friendIds?: string[];
  /** Live event the viewer is checked in to, if any. */
  checkedInEvent?: LiveEvent | null;
  /** Unread notification count (bell badge). Default 3. */
  unreadCount?: number;
  /** Paint the app's dark background behind children. Default true. */
  background?: boolean;
}

export const SAMPLE_USER: SideBetUser = {
  userId: 'user-jordan',
  username: 'jordan.miles',
  displayName: 'Jordan Miles',
  role: 'USER',
  subscriptionTier: 'FREE',
};

// Configure the data client once, against an unreachable host: components'
// own AWS calls then fail over the network into their catch blocks (empty /
// error states) instead of throwing synchronously and blanking the render.
if ((canvasAmplifyConfig as { data?: unknown }).data && !Amplify.getConfig().API) {
  Amplify.configure(canvasAmplifyConfig as Parameters<typeof Amplify.configure>[0]);
}

const noop = () => {};
const asyncNoop = async () => {};

/**
 * Wrap SideBet components in this on the design canvas. Supplies the app's
 * auth, profile, bet-data, event check-in and notification contexts with
 * sample data, plus safe-area insets, so data-bound components render.
 */
export const SideBetProvider: React.FC<SideBetProviderProps> = ({
  children,
  user = SAMPLE_USER,
  balance = 250,
  myBets = [],
  joinableBets = [],
  betInvitations = [],
  squaresInvitations = [],
  mySquaresGames = [],
  joinableSquaresGames = [],
  myParticipation = {},
  friendIds = [],
  checkedInEvent = null,
  unreadCount = 3,
  background = true,
}) => {
  const auth = useMemo(() => ({
    user: user && {
      role: 'USER',
      onboardingCompleted: true,
      onboardingStep: 0,
      subscriptionTier: 'FREE',
      subscriptionStatus: 'ACTIVE',
      ...user,
    },
    isLoading: false,
    signOut: asyncNoop,
    refreshAuth: asyncNoop,
    patchUser: noop,
  }), [user]);

  const profile = useMemo(() => ({
    profile: user ? {
      id: user.userId,
      email: `${user.username}@example.com`,
      displayName: user.displayName,
      profilePictureUrl: user.profilePictureUrl,
      balance,
      role: user.role ?? 'USER',
      trustScore: 5,
    } : null,
    balance,
    isLoading: false,
    refresh: asyncNoop,
    applyUpdate: noop,
  }), [user, balance]);

  const betData = useMemo(() => ({
    myBets,
    joinableBets,
    joinableFriendsBets: joinableBets.filter((b) => friendIds.includes(b.creatorId)),
    mySquaresGames,
    joinableSquaresGames,
    joinableFriendsSquaresGames: joinableSquaresGames.filter((g) => friendIds.includes(g.creatorId)),
    myParticipation: new Map(Object.entries(myParticipation)),
    friendIds: new Set(friendIds),
    betInvitations,
    squaresInvitations,
    isInitialLoading: false,
    isRefreshing: false,
    refresh: asyncNoop,
    acceptBetInvitation: async () => true,
    declineBetInvitation: asyncNoop,
    declineSquaresInvitation: asyncNoop,
    dismissSquaresInvitationByGame: noop,
  }), [myBets, joinableBets, betInvitations, squaresInvitations, mySquaresGames, joinableSquaresGames, myParticipation, friendIds]);

  const checkIn = useMemo(() => ({
    checkedInEvent,
    nearbyEventsCount: 2,
    showEventDiscovery: false,
    isLoading: false,
    setShowEventDiscovery: noop,
    handleCheckInPress: noop,
    handleCheckOut: asyncNoop,
    handleCheckInSuccess: noop,
    refreshCheckInState: asyncNoop,
    refreshNearbyEventsCount: asyncNoop,
  }), [checkedInEvent]);

  const notifications = useMemo(() => ({
    unreadCount,
    refreshUnreadCount: asyncNoop,
    markAsRead: asyncNoop,
    markAllAsRead: asyncNoop,
  }), [unreadCount]);

  return (
    <SafeAreaProvider
      initialMetrics={{ frame: { x: 0, y: 0, width: 390, height: 844 }, insets: { top: 0, left: 0, right: 0, bottom: 0 } }}
    >
      <AuthContext.Provider value={auth}>
        <ProfileContext.Provider value={profile}>
          <BetDataContext.Provider value={betData}>
            <EventCheckInContext.Provider value={checkIn}>
              <NotificationContext.Provider value={notifications}>
                {/* Root navigation for components that call useNavigation()
                    (Header). Independent so it never nests into a host app's tree. */}
                <NavigationIndependentTree>
                  <NavigationContainer>
                    {background
                      ? <View style={{ backgroundColor: colors.background, flexGrow: 1 }}>{children}</View>
                      : children}
                  </NavigationContainer>
                </NavigationIndependentTree>
              </NotificationContext.Provider>
            </EventCheckInContext.Provider>
          </BetDataContext.Provider>
        </ProfileContext.Provider>
      </AuthContext.Provider>
    </SafeAreaProvider>
  );
};
